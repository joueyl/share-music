/** Versioned, additive schema. Run before accepting traffic; never drops existing data. */
export const MYSQL_SCHEMA = [
`CREATE TABLE IF NOT EXISTS schema_migrations (version INT PRIMARY KEY, applied_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP) ENGINE=InnoDB`,
`CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) PRIMARY KEY, name VARCHAR(254) NOT NULL UNIQUE, email VARCHAR(254) NULL UNIQUE,
 display_name VARCHAR(80) NOT NULL DEFAULT '', avatar_url VARCHAR(2048) NULL,
 password_hash VARCHAR(128) NOT NULL, salt VARCHAR(64) NOT NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin`,
`CREATE TABLE IF NOT EXISTS rooms (
 id CHAR(36) PRIMARY KEY, name VARCHAR(80) NOT NULL, host_id CHAR(36) NOT NULL,
 description VARCHAR(500) NOT NULL DEFAULT '', atmosphere VARCHAR(16) NOT NULL DEFAULT 'sunset',
 visibility VARCHAR(16) NOT NULL DEFAULT 'public', category VARCHAR(40) NOT NULL DEFAULT '', cover_url VARCHAR(2048) NULL,
 invite_code VARCHAR(32) NOT NULL UNIQUE, defaults_json JSON NOT NULL, overrides_json JSON NOT NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 INDEX idx_rooms_discovery(visibility,category), CONSTRAINT fk_rooms_host FOREIGN KEY(host_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin`,
`CREATE TABLE IF NOT EXISTS songs (
 sequence BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, scope VARCHAR(256) NOT NULL, source VARCHAR(128) NOT NULL,
 content_hash CHAR(64) NULL, name VARCHAR(200) NOT NULL DEFAULT '', artists VARCHAR(1000) NOT NULL DEFAULT '', album VARCHAR(500) NOT NULL DEFAULT '',
 cover_url VARCHAR(2048) NULL, duration_ms INT UNSIGNED NULL, size_bytes BIGINT UNSIGNED NULL, lossless BOOLEAN NOT NULL DEFAULT FALSE,
 bitrate_bps INT UNSIGNED NULL, sample_rate INT UNSIGNED NULL, bits TINYINT UNSIGNED NULL, channels TINYINT UNSIGNED NULL,
 oss_key VARCHAR(500) NULL, netease_id VARCHAR(20) NULL, track_json JSON NULL, detail_json JSON NULL,
 created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 UNIQUE KEY uq_song_source(scope,source), INDEX idx_song_hash(scope,content_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin`,
`CREATE TABLE IF NOT EXISTS room_tracks (
 room_id CHAR(36) NOT NULL, track_id CHAR(36) NOT NULL, position INT UNSIGNED NOT NULL, provider_id CHAR(36) NOT NULL, track_json JSON NOT NULL,
 PRIMARY KEY(room_id,track_id), UNIQUE KEY uq_room_position(room_id,position),
 CONSTRAINT fk_room_tracks_room FOREIGN KEY(room_id) REFERENCES rooms(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin`,
`CREATE TABLE IF NOT EXISTS music_assets (
 sequence BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, scope VARCHAR(256) NOT NULL, hash CHAR(64) NOT NULL, oss_key VARCHAR(500) NOT NULL,
 UNIQUE KEY uq_asset(scope,hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin`,
`CREATE TABLE IF NOT EXISTS settings (setting_key VARCHAR(100) PRIMARY KEY, value MEDIUMTEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin`,
`INSERT IGNORE INTO schema_migrations(version) VALUES(1)`
];
